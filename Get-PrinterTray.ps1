
param(
    [Parameter(Mandatory = $true)]
    [string]$printerName
)

Add-Type @'
using System;
using System.Runtime.InteropServices;

public class PrinterBins
{
    [DllImport("winspool.drv", CharSet = CharSet.Unicode)]
    public static extern int DeviceCapabilities(
        string device, string port, short capability,
        IntPtr output, IntPtr devmode);
}
'@

$printer = Get-CimInstance Win32_Printer |
    Where-Object Name -eq $printerName

if (-not $printer) {
    throw "Printer not found: $printerName"
}

# DC_BINS = 6; DC_BINNAMES = 12
$binCount = [PrinterBins]::DeviceCapabilities(
    $printer.Name, $printer.PortName, 6,
    [IntPtr]::Zero, [IntPtr]::Zero
)

$nameCount = [PrinterBins]::DeviceCapabilities(
    $printer.Name, $printer.PortName, 12,
    [IntPtr]::Zero, [IntPtr]::Zero
)

if ($binCount -le 0 -or $binCount -ne $nameCount) {
    throw "Unable to retrieve matching tray identifiers and names."
}

$binBuffer = [Runtime.InteropServices.Marshal]::AllocHGlobal(
    $binCount * 2
)
$nameBuffer = [Runtime.InteropServices.Marshal]::AllocHGlobal(
    $nameCount * 24 * 2
)

try {
    [void][PrinterBins]::DeviceCapabilities(
        $printer.Name, $printer.PortName, 6,
        $binBuffer, [IntPtr]::Zero
    )

    [void][PrinterBins]::DeviceCapabilities(
        $printer.Name, $printer.PortName, 12,
        $nameBuffer, [IntPtr]::Zero
    )

    for ($i = 0; $i -lt $binCount; $i++) {
        $id = [Runtime.InteropServices.Marshal]::ReadInt16(
            $binBuffer, $i * 2
        ) -band 0xFFFF

        $name = [Runtime.InteropServices.Marshal]::PtrToStringUni(
            [IntPtr]::Add($nameBuffer, $i * 48)
        )

        [PSCustomObject]@{
            TrayCode = $id
            TrayName = $name
        }
    }
}
finally {
    [Runtime.InteropServices.Marshal]::FreeHGlobal($binBuffer)
    [Runtime.InteropServices.Marshal]::FreeHGlobal($nameBuffer)
}

